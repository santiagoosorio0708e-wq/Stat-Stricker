-- ============================================================================
-- StatStriker - Script SQL de esquema relacional y datos iniciales coherentes
-- Compatible con PostgreSQL y H2 (MODE=PostgreSQL)
-- ============================================================================

CREATE TABLE IF NOT EXISTS usuarios (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(100) NOT NULL,
    correo          VARCHAR(150) NOT NULL UNIQUE,
    area            VARCHAR(80)  NOT NULL,
    fecha_creacion  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_usuarios_correo ON usuarios (correo);

CREATE TABLE IF NOT EXISTS categorias (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(100) NOT NULL UNIQUE,
    descripcion     VARCHAR(300) NOT NULL,
    liga_codigo     VARCHAR(32)  DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_categorias_nombre ON categorias (nombre);

CREATE TABLE IF NOT EXISTS analisis_casos (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo           VARCHAR(180) NOT NULL,
    descripcion      TEXT         NOT NULL,
    categoria_id     BIGINT       NOT NULL REFERENCES categorias(id),
    prioridad        VARCHAR(20)  NOT NULL CHECK (prioridad IN ('ALTA', 'MEDIA', 'BAJA')),
    estado           VARCHAR(20)  NOT NULL CHECK (estado IN ('PENDIENTE', 'EN_ANALISIS', 'RESUELTO', 'CERRADO')),
    fecha_creacion   TIMESTAMP    NOT NULL,
    fecha_resolucion TIMESTAMP    NULL,
    usuario_id       BIGINT       NOT NULL REFERENCES usuarios(id)
);
CREATE INDEX IF NOT EXISTS idx_casos_estado ON analisis_casos (estado);
CREATE INDEX IF NOT EXISTS idx_casos_prioridad ON analisis_casos (prioridad);
CREATE INDEX IF NOT EXISTS idx_casos_categoria ON analisis_casos (categoria_id);
CREATE INDEX IF NOT EXISTS idx_casos_fecha ON analisis_casos (fecha_creacion);

CREATE TABLE IF NOT EXISTS articulos_conocimiento (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo              VARCHAR(180) NOT NULL,
    problema            TEXT         NOT NULL,
    sintomas            TEXT         NOT NULL,
    causa               TEXT         NOT NULL,
    solucion            TEXT         NOT NULL,
    categoria_id        BIGINT       NOT NULL REFERENCES categorias(id),
    activo              BOOLEAN      NOT NULL DEFAULT TRUE,
    verificado          BOOLEAN      NOT NULL DEFAULT TRUE,
    fecha_creacion      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_articulos_activo ON articulos_conocimiento (activo, verificado);
CREATE INDEX IF NOT EXISTS idx_articulos_categoria ON articulos_conocimiento (categoria_id);

CREATE TABLE IF NOT EXISTS consultas_ia (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id      VARCHAR(80)  NOT NULL,
    analisis_id     BIGINT       NULL REFERENCES analisis_casos(id),
    usuario_id      BIGINT       NULL REFERENCES usuarios(id),
    pregunta        TEXT         NOT NULL,
    estado          VARCHAR(20)  NOT NULL CHECK (estado IN ('PENDIENTE', 'RESPONDIDA', 'SIN_RESULTADOS', 'ERROR')),
    fecha           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_consultas_session ON consultas_ia (session_id, fecha);
CREATE INDEX IF NOT EXISTS idx_consultas_estado ON consultas_ia (estado);

CREATE TABLE IF NOT EXISTS respuestas_ia (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consulta_id     BIGINT       NOT NULL UNIQUE REFERENCES consultas_ia(id) ON DELETE CASCADE,
    respuesta       TEXT         NOT NULL,
    modelo          VARCHAR(100) NOT NULL,
    fecha           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS fuentes_respuesta (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    respuesta_id    BIGINT       NOT NULL REFERENCES respuestas_ia(id) ON DELETE CASCADE,
    articulo_id     BIGINT       NULL REFERENCES articulos_conocimiento(id) ON DELETE SET NULL,
    titulo_fuente   VARCHAR(220) NOT NULL,
    categoria       VARCHAR(60)  NOT NULL,
    similitud       DOUBLE PRECISION NOT NULL DEFAULT 0.0
);
CREATE INDEX IF NOT EXISTS idx_fuentes_respuesta ON fuentes_respuesta (respuesta_id);

CREATE TABLE IF NOT EXISTS calificaciones (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    respuesta_id    BIGINT       NOT NULL UNIQUE REFERENCES respuestas_ia(id) ON DELETE CASCADE,
    puntuacion      INTEGER      NOT NULL CHECK (puntuacion BETWEEN 1 AND 5),
    comentario      VARCHAR(500) DEFAULT '',
    fecha           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

